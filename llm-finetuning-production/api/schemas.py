"""
Pydantic Schemas for Request/Response Validation
"""
from typing import Optional
from pydantic import BaseModel, Field, ConfigDict

class ExtractionRequest(BaseModel):
    """Input payload for structured order extraction."""
    text: str = Field(
        ...,
        min_length=3,
        max_length=2000,
        description="Raw unstructured text containing customer order instructions.",
        json_schema_extra={"example": "John ordered 3 laptops for $2400 and wants delivery on Friday."}
    )
    temperature: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description="Sampling temperature (0.0 for deterministic greedy extraction)."
    )

class OrderDetails(BaseModel):
    """Structured extraction target schema."""
    customer: str = Field(..., description="Customer name")
    quantity: int = Field(..., description="Quantity of items purchased")
    product: str = Field(..., description="Name/description of product")
    amount: float = Field(..., description="Total monetary amount billed")
    delivery_day: str = Field(..., description="Target delivery day or window")

    model_config = ConfigDict(extra="ignore")

class ExtractionResponse(BaseModel):
    """API output response model."""
    data: Optional[OrderDetails] = Field(None, description="Validated parsed order details (null if parsing failed)")
    raw_response: str = Field(..., description="Raw text generated by the fine-tuned LLM")
    is_valid_json: bool = Field(..., description="True if output was valid JSON conforming to schema")
    error: Optional[str] = Field(None, description="Error explanation if JSON parsing failed")
    latency_ms: float = Field(..., description="End-to-end inference latency in milliseconds")
    model_name: str = Field(..., description="Model identifier used for inference")

class HealthResponse(BaseModel):
    """API health status response."""
    status: str = Field("healthy", description="Service health state")
    model: str = Field(..., description="Active model path or ID")
    device: str = Field(..., description="Compute device (cuda/cpu)")
